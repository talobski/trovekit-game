import { readFileSync } from "node:fs"
import { test, expect } from "./browser-fixtures"
import { adminNav, axe, noOverflow } from "./helpers"
import { starfallContent } from "../tests/fixtures/starfall"

const ADMIN = "http://127.0.0.1:5281"
const headers = { "x-trovekit-admin": "1" }
for (const width of [390, 1280]) test(`name to reviewed batch and published pack at ${width}`, async ({ page, context }) => {
  await page.setViewportSize({ width, height: 900 })
  await context.grantPermissions(["clipboard-read", "clipboard-write"], { origin: ADMIN })
  await page.goto(ADMIN)
  await adminNav(page, "Library")
  await page.getByRole("link", { name: "New pack" }).first().click()
  await expect(page.getByLabel("New pack ID")).toHaveCount(0)
  await page.getByLabel("Pack name", { exact: true }).fill("  ")
  await page.getByRole("button", { name: "Create manually instead", exact: true }).click()
  await expect(page.getByLabel("Pack name", { exact: true })).toBeFocused()
  await expect(page.getByText("Enter a pack name.")).toBeVisible()
  const name = `Moon Garden ${width}`, id = `moon-garden-${width}`
  await page.getByLabel("Pack name", { exact: true }).fill(name)
  await page.getByRole("button", { name: "Create manually instead", exact: true }).click()
  // Only a name: the new pack's Overview opens with its setup checklist.
  await expect(page).toHaveURL(new RegExp(`#/packs/${id}$`))
  await expect(page.getByRole("list", { name: "Setup steps" })).toContainText("Add cards: To do")
  await expect(page.getByText("Draft: add cards to publish", { exact: true })).toBeVisible()
  await page.getByRole("list", { name: "Setup steps" }).getByRole("link", { name: "Cards", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Cards", level: 1 })).toBeFocused()
  await expect(page.getByRole("button", { name: "Publish version", exact: true })).toBeDisabled()
  await expect(page.getByRole("button", { name: "Import cards", exact: true })).toBeVisible()
  await noOverflow(page); await axe(page, `new creator ${width}`)
  await page.screenshot({ path: `test-results/evidence/creator-${width}-empty.png`, fullPage: true })
  await adminNav(page, "Resources")
  await page.getByLabel("Label (resource-1)", { exact: true }).fill("Petals")
  await adminNav(page, "Settings")
  await page.getByLabel("Name", { exact: true }).fill(`${name} renamed`)
  await page.getByRole("button", { name: "Save draft", exact: true }).click()
  await expect(page.getByText("Draft saved. It stays private until you publish a version.", { exact: true })).toBeVisible()
  const saved = await (await page.request.get(`${ADMIN}/admin-api/drafts/${id}`, { headers })).json()
  expect(saved).toMatchObject({ source: "draft", content: { pack: { id, name: `${name} renamed`, cards: [] } } })
  // A refresh reopens the unfinished draft, not the default pack.
  await page.reload()
  await expect(page.getByRole("banner")).toContainText(`${name} renamed · Draft`)
  await adminNav(page, "Library")
  // Nothing unsaved, so opening from the library needs no confirmation.
  await page.getByRole("link", { name: `Continue draft: ${name} renamed`, exact: true }).click()
  await adminNav(page, "Cards")
  await page.getByRole("button", { name: "Generate cards with AI", exact: true }).click()
  await page.getByRole("dialog", { name: "Generate cards with AI" }).getByRole("button", { name: "Copy AI prompt", exact: true }).click()
  await expect(page.getByText("Prompt copied. Paste it into your AI assistant.", { exact: true })).toBeVisible()
  const clipboard = await page.evaluate(() => navigator.clipboard.readText())
  expect(clipboard).toContain('"label": "Petals"')
  expect(clipboard).toContain('"name": "Moon Garden')
  expect(clipboard).toContain('"schemaVersion": 2')
  await page.getByRole("button", { name: "View prompt and example" }).click()
  await expect(page.getByLabel("Prompt for your AI assistant", { exact: true })).toHaveValue(clipboard)
  await noOverflow(page); await axe(page, `creator prompt ${width}`)
  await page.screenshot({ path: `test-results/evidence/creator-${width}-prompt.png`, fullPage: true })
  const download = page.waitForEvent("download")
  await page.getByRole("button", { name: "Download example", exact: true }).click()
  const file = await (await download).path()
  const example = JSON.parse(readFileSync(file, "utf8"))
  await page.keyboard.press("Escape")
  await page.getByLabel("Import cards file").setInputFiles({ name: "example.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(example)) })
  await expect(page.getByRole("button", { name: "Apply to editor" })).toBeDisabled()
  await expect(page.getByText("This batch can be applied to your draft. Fix these requirements before publishing.")).toBeVisible()
  await page.getByRole("switch", { name: "Apply this batch to my draft", exact: true }).click()
  await page.getByRole("button", { name: "Apply to editor" }).click()
  await expect(page.getByRole("button", { name: "Publish version" })).toBeDisabled()
  await page.getByRole("button", { name: "Save draft", exact: true }).click()
  await expect.poll(async () => (await (await page.request.get(`${ADMIN}/admin-api/drafts/${id}`, { headers })).json()).content.pack.cards.length).toBe(3)

  // Bad CSV gives a persistent row/field correction, never alters the editor.
  await page.getByLabel("Import cards file").setInputFiles({ name: "bad.csv", mimeType: "text/csv", buffer: Buffer.from("id,group,name,permanentResource,points\na,tier-1,A,resource-1,nope") })
  await expect(page.getByRole("alert")).toContainText("CSV row 2 (points): Enter a whole number")
  await page.screenshot({ path: `test-results/evidence/creator-${width}-import-error.png`, fullPage: true })
  // A complete fixture-derived batch replaces the examples using their existing IDs.
  const source = starfallContent()
  const groups = Object.fromEntries(source.pack.cardGroups.map((g, i) => [g.id, saved.content.pack.cardGroups[i].id]))
  const kinds = Object.fromEntries(source.pack.resourceKinds.map((k, i) => [k.id, saved.content.pack.resourceKinds[i].id]))
  const cards = source.pack.cards.map((c, i) => ({ id: i < 3 ? example[i].id : `garden-${i}`, name: `Garden card ${i}`, group: groups[c.group], permanentResource: kinds[c.permanentResource], points: c.points, cost: Object.fromEntries(Object.entries(c.cost).map(([k, v]) => [kinds[k], v])) }))
  const batch = { name: "garden.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(cards)) }
  await page.getByLabel("Import cards file").setInputFiles(batch)
  await expect(page.getByText(/63 new cards; 3 existing IDs replaced/)).toBeVisible()
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(page.getByText("3 cards in this draft. Select any card to edit it.")).toBeVisible()
  await page.getByLabel("Import cards file").setInputFiles(batch)
  await expect(page.getByRole("button", { name: "Apply to editor" })).toBeDisabled()
  await noOverflow(page); await axe(page, `creator batch review ${width}`)
  await page.screenshot({ path: `test-results/evidence/creator-${width}-review.png`, fullPage: true })
  await page.getByRole("switch", { name: "Apply this batch and replace 3 existing cards in my draft", exact: true }).click()
  await page.getByRole("button", { name: "Apply to editor" }).click()
  await expect(page.getByText("Ready to publish", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: /Garden card 0/ }).click()
  await page.getByLabel("Name", { exact: true }).fill("Garden card refined")
  await page.keyboard.press("Escape")
  await page.screenshot({ path: `test-results/evidence/creator-${width}-cards.png`, fullPage: true })
  await page.getByRole("button", { name: "Publish version", exact: true }).click()
  await page.getByRole("button", { name: "Publish", exact: true }).click()
  await page.getByRole("button", { name: "Not now" }).click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  // Published but not the default: the admin lists the version; players are not offered it.
  expect((await (await page.request.get(`${ADMIN}/admin-api/content`, { headers })).json()).versions.some((v: { packId: string }) => v.packId === id)).toBe(true)
  expect((await (await page.request.get("http://localhost:5280/api/packs")).json()).map((p: { packId: string }) => p.packId)).toEqual(["starfall"])
})

test("clipboard denial offers a selectable prompt and keyboard dismissal", async ({ page }) => {
  await page.goto(`${ADMIN}/#/packs/starfall/cards`)
  await page.evaluate(() => { Object.defineProperty(navigator, "clipboard", { value: { writeText: async () => { throw new Error("Clipboard denied") } }, configurable: true }) })
  await page.getByRole("button", { name: "Generate cards with AI", exact: true }).click()
  await page.getByRole("button", { name: "Copy AI prompt", exact: true }).click()
  await expect(page.getByText("Your browser did not allow copying. Select the prompt below and copy it.")).toBeVisible()
  const prompt = page.getByLabel("Prompt for your AI assistant", { exact: true })
  await expect(prompt).toBeFocused()
  expect(await prompt.evaluate((node: HTMLTextAreaElement) => node.selectionEnd - node.selectionStart)).toBeGreaterThan(100)
  await page.keyboard.press("Escape")
  await expect(page.getByRole("button", { name: "Generate cards with AI", exact: true })).toBeFocused()
})
